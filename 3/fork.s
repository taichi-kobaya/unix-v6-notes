// Cライブラリ側からforkシステムコールを起動するアセンブリラッパー
// 
// pid = fork();
// 
// 子プロセスではpid == 0,エラー時はpid == -1が返る
// 子プロセス側では必要に応じて親のID(par_uid)が参照できる


.global _fork, cerror, _par_uid

_fork:  // UNIX V6のコンパイラではCの関数は先頭に_のついたラベルに変換される = fork()
    // PDP-11の標準関数プロローグ：旧フレームポインタr5をスタックに退避し、現在のspを新r5にする
    mov     r5,-(sp)
    mov     sp,r5
    // forkシステムコールを発行してカーネルモードへ遷移する
    sys fork    // sysはシステムコールを発行するアセンブラ命令

    // sys forkの直後に置かれた「子プロセス側が復帰するアドレス」へ飛ぶ
    // (カーネル側で子プロセスの戻りアドレスがここを指すように調整される)
        br 1f
    
    // 親プロセス側（またはエラー時）はsys forkの次の命令へ戻って来る
    // キャリービットがクリア（エラーなし）なら2fへジャンプ
    bec 2f

    // キャリービットがセットされている場合はシステムコール失敗
    // エラーコード（u.u_error）をerrnoにセットする共通ルーチンcerrorへ飛ぶ
    jmp     cerror
1:
    // --- 子プロセス側の処理 ---
    // カーネルから子プロセスへ返されたr0（親のPID等）を_par_uidに保存する
    mov     r0,_par_uid

    // C言語の仕様通り、子プロセスにおけるfork()の戻り値（r0）を0にする
    clr r0
2:
    // --- 正常終了時のエピローグ（親・子共通） ---
    // 退避していたrをスタックから復元し、呼び出し元へ戻る（rts pc）
    mov     (sp)+,r5
    rts pc
.bss
// 未初期化データ領域（BSS）：親の識別情報などを保持する2バイト（1ワード）領域
_par_uid: .=.+2
