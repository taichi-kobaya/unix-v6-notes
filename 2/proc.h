/*proc構造体
*構造体配列proc[]の各エントリが1つのプロセスに対応している。
*プロセスの状態や実行優先度など、プロセスに関する情報のうち、
*常にカーネルから必要とされる情報を扱う。
*/
struct proc
{
    char    p_stat;     /*状態。NULLの場合はそのproc[]エントリは空だとみなされる。【プロセスの状態】を参照*/
    char    p_flag;     /*フラグ。【プロセスのフラグ】を参照*/
    char    p_pri;      /*実行優先度。値が小さいほど優先度が高く、次に実行されやすくなる。*/
    char    p_sig;      /*このプロセスに送信されるシグナル番号*/
    char    p_uid;      /*ユーザーID　ttyシグナルの送信に使用*/
    char    p_time;     /*メモリまたはスワップ領域に存在している時間（秒）*/
    char    p_cpu;      /*CPUを使用した累積時間（ティック）*/
    char    p_nice;     /*実行優先度を下げる補正値。デフォルトは0で、niceシステムコールによりユーザが好きな値を設定できる。*/
    int p_ttyp;         /*プロセスを操作している端末*/
    int p_pid;          /*一意のプロセスID*/
    int p_ppid;         /*親プロセスのプロセスID*/
    int p_addr;         /*割り当てられたメモリの物理アドレス（64バイト単位）*/
    int p_size;         /*割り当てられたメモリのサイズ（64バイト単位）*/
    int p_wchan;        /*スリープしている理由*/
    int *p_textp;       /*使用しているテキストセグメント（text構造体へのポインタ）*/
} proc[NPROC];      /*エントリ数はNPROC 50と定義されている*/

/*プロセスの状態*/
#define SSLEEP 1       /*休眠状態。実行優先度が負でスリープしている。*/
#define SWAIT  2       /*休眠状態。実行優先度が0以上でスリープしている。*/
#define SRUN   3       /*実行可能状態*/
#define SIDL   4       /*プロセス生成処理中*/
#define SZOMB  5       /*ゾンビ状態（プロセス終了の中間状態）*/
#define SSTOP  6       /*トレースによる介入待ち*/

/*プロセスのフラグ*/
#define SLOAD  01       /*メモリ上に存在する（スワップアウトされていない）*/
#define SSYS   02       /*システムプロセスであり、スワップ対象にならない。UNIX V6ではproc[0]のみ。*/
#define SLOCK  04       /*スワップアウトしてはいけない*/
#define SSWAP  010      /*スワップアウトにより、user.u_rsav[]の値が不正。user.u_ssav[]からr5,r6を復帰しなければならない。*/
#define STRC   020      /*トレースされている*/
#define SWTED  040      /*トレース処理に使用*/

