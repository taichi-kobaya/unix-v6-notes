/*
*user構造体
*プロセスがオープンしたファイルやカレントディレクトリ情報などを扱う。
*実行プロセス以外のuser構造体はカーネルから必要とされないため、対応するプロセスが
*スワップアウトされる時には一緒にスワップアウトされる。
*/
struct user
{
    int u_rsav[2];          /*プロセスの切り替え時に、実行中のr5,r6を退避しておく領域*/
    int u_fsav[25];         /*PDP-11/40環境では使用しない*/
    char    u_segflg;       /*ファイルの読み書きに使用されるフラグ*/
    char    u_error;            /*エラー時にエラーコードが格納される。【エラーコード】を参照*/
    char    u_uid;              /*実効ユーザID*/
    char    u_gid;              /*実効グループID*/
    char    u_ruid;             /*実ユーザID*/
    char    u_rgid;             /*実グループID*/
    int u_procp;            /*この構造体に対応したproc[]エントリを指す*/
    char    *u_base;            /*ファイルの読み書きをする時に、パラメータを渡すために使用される*/
    char    *u_count;           /*ファイルの読み書きをする時に、パラメータを渡すために使用される*/
    char    *u_offset[2];       /*ファイルの読み書きをする時に、パラメータを渡すために使用される*/
    int *u_cdir;            /*カレントディレクトリのinode[]エントリ*/
    char    u_dbuf[DIRSIZ];     /*namei()で使用される作業領域。ファイル、ディレクトリ名が格納される。*/
    char    *u_dirp;            /*ユーザプログラム、もしくはカーネルプログラムから与えられたファイルのパス名を読み込む時に使用される*/
    struct {
        int u_ino;      /*inode番号*/
        char    u_name[DIRSIZ];     /*ファイル、ディレクトリ名*/
    } u_dent;       /*namei()で使用される作業領域。ディレクトリエントリが格納される。*/
    int u_pdir;             /*namei()で対象ファイル、ディレクトリの親ディレクトリが格納される*/    
    int u_uisa[16];         /*ユーザPARの値*/
    int u_uisd[16];         /*ユーザPDRの値*/
    int u_ofile[NOFILE];    /*そのプロセスがオープンしているファイル*/
    int u_arg[5];           /*システムコール処理でユーザプログラムから引数を渡す時などに使用される*/
    int u_tsize;            /*テキストセグメントのサイズ（64バイト単位）*/
    int u_dsize;            /*データ領域のサイズ（64バイト単位）*/
    int u_ssize;            /*スタック領域のサイズ（64バイト単位）*/
    int u_sep;              /*PDP-11/40環境では基本的に0*/
    int u_qsav[2];          /*システムコール処理中にシグナル処理が発生した時に使用されるr5,r6の退避領域*/
    int u_ssav[2];          /*スワップアウト処理により、user.u_rsav[]の値が不正な時に使用されるr5,r6の退避領域*/
    int u_signal[NSIG];     /*シグナルを受信した時の動作を設定するために使用される*/
    int u_utime;            /*ユーザモードとしてCPUを使用した時間（ティック）*/
    int u_stime;            /*カーネルモードとしてCPUを使用した時間（ティック）*/
    int u_cutime[2];        /*子プロセスがユーザモードとしてCPUを使用した時間（ティック）*/
    int u_cstime[2];        /*子プロセスがカーネルモードとしてCPUを使用した時間（ティック）*/
    int *u_ar0;             /*システムコール処理時にユーザプロセスの汎用レジスタやPSWを操作する時に使用される*/
    int u_prof[4];          /*プロファイル用*/
    char    u_intflg;           /*システムコール処理中にシグナル処理が発生したかどうかを判定するフラグ*/

} u;

/*エラーコード*/
#define EFAULT  106    /*ユーザ空間とカーネル空間の間でデータ転送を失敗したなど*/
#define EPERM   1      /*スーパーユーザでない*/
#define ENOENT  2      /*指定されたファイルが存在しない*/
#define ESRCH   3      /*シグナルを送る先のプロセスが存在しないか、すでに消滅していた*/
#define EINTR   4      /*システムコール処理中にシグナル処理をした*/
#define EIO 5          /*I/Oエラー*/
#define ENXIO   6      /*デバイス番号で示されたデバイスが存在しない*/
#define E2BIG   7      /*execシステムコールで実行プログラムへ512バイト以上の引数リストが与えられた*/
#define ENOEXEC 8      /*実行プログラムのフォーマット（マジックナンバ）が不正*/
#define EBADF   9      /*オープンしていないファイルを操作しようとしているか、読み取り専用、もしくは書き込み専用モードでオープンしたファイルにたいしてwriteもしくはreadを行おうとした*/
#define ECHILD  10     /*waitシステムコールで、子プロセスが見つからなかった*/
#define EAGAIN  11     /*forkシステムコールで、proc[]に空きエントリが見つからなかった*/
#define ENOMEM  12     /*プロセスに対して、使用可能なメモリ容量以上のメモリ領域を割り当てようとした*/
#define EACCES  13     /*ファイル、ディレクトリのアクセス権限がない*/
#define ENOTBLK 15     /*ブロックデバイスのスペシャルファイルではない*/
#define EBUSY   16     /*mount,umountシステムコールで、対象マウントポイントが使用中*/
#define EEXIST  17     /*linkシステムコールなどで、すでにそのファイルが存在する*/
#define EXDEV   18     /*別のデバイスのファイルに対してリンクを張ろうとした*/
#define ENODEV  19     /*デバイス番号で示されたデバイスは存在しない*/
#define ENOTDIR 20     /*ディレクトリではない*/
#define EISDIR  21     /*ディレクトリに対して書き込みを行おうとした*/
#define EINVAL  22     /*パラメータが不正*/
#define ENFILE  23     /*file[]があふれた*/
#define EMFILE  24     /*user.u_ofile[]があふれた*/
#define ENOTTY  25     /*端末のスペシャルファイルではない*/
#define ETXTBSY 26     /*テキストセグメントとして割り当てようとしたプログラムファイルが、他のプロセスによりデータファイルとして使用されていた。もしくはテキストセグメントとして割り当てられたファイルに対して書き込もうとした。*/
#define EFBIG   27     /*ファイルサイズが大きすぎる*/
#define ENOSPC  28     /*ブロックデバイスの容量が足りない*/
#define ESPIRE  29     /*パイプファイルに対してseekシステムコールを実行した*/
#define EROFS   30     /*読み取り専用でマウントされたブロックデバイスのファイルやディレクトリを更新しようとした*/
#define EMLINK  31     /*リンク数が多すぎる*/
#define EPIPE   32     /*壊れたパイプファイル*/
